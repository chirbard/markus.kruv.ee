TAP_COORDINATES = 4

HEADER = "/* Generated by tools/seq-css.py; do not edit. */"


def slide_keyframes(
    ident: str, start: float, end: float, hold_end: int, axis: str = "X"
) -> str:
    """Build a sliding page transition."""
    return f"""@keyframes {ident} {{
  0%,
  {start}% {{
    transform: translate{axis}(100%);
    opacity: 1;
    animation-timing-function: cubic-bezier(0.2, 0.8, 0.2, 1);
  }}

  {end}%,
  {hold_end}% {{
    transform: translate{axis}(0);
    opacity: 1;
  }}

  99% {{
    transform: translate{axis}(0);
    opacity: 0;
  }}

  100% {{
    transform: translate{axis}(100%);
    opacity: 0;
  }}
}}
"""


def fade_keyframes(ident: str, start: float, end: float, hold_end: int) -> str:
    """Build an opacity transition."""
    return f"""@keyframes {ident} {{
  0%,
  {start}% {{
    opacity: 0;
  }}

  {end}%,
  {hold_end}% {{
    opacity: 1;
  }}

  99%,
  100% {{
    opacity: 0;
  }}
}}
"""


def tap_keyframes(ident: str, start: float, end: float) -> str:
    """Build the tap appearance, press and release."""
    return f"""@keyframes {ident} {{
  0%,
  {start}% {{
    opacity: 0;
    transform: scale(0.6);
  }}

  {start + 1.5:g}% {{
    opacity: 1;
    transform: scale(1);
  }}

  {start + 3.5:g}% {{
    opacity: 1;
    transform: scale(0.85);
  }}

  {end}%,
  100% {{
    opacity: 0;
    transform: scale(1.2);
  }}
}}
"""


def swipe_keyframes(ident: str, start: float, end: float, dy: float) -> str:
    """Build a finger movement along the screen."""
    moved = f"calc(var(--tap-y) + {dy}%)"
    return f"""@keyframes {ident} {{
  0%,
  {start}% {{
    opacity: 0;
    top: var(--tap-y);
  }}

  {start + 1.5:g}% {{
    opacity: 1;
    top: var(--tap-y);
    animation-timing-function: ease-in-out;
  }}

  {end - 1.5:g}% {{
    opacity: 1;
    top: {moved};
  }}

  {end}%,
  100% {{
    opacity: 0;
    top: {moved};
  }}
}}
"""


def generate() -> str:
    """Render every timeline into CSS rules and keyframes."""
    places = []
    rules = []
    frames = []
    for name, seq in SEQUENCES.items():
        seconds = seq["seconds"]
        selector = seq["selector"]
        prefix = seq["step_prefix"]
        for index, (enter, (start, end), tap) in enumerate(seq["steps"], start=2):
            ident = f"{name}-{seq['frame_step']}{index}"
            rules.append(
                f"  {selector} .{prefix}{index} {{\n"
                f"    animation: {ident} {seconds}s{seq['delay']} infinite both;\n"
                f"  }}\n",
            )
            if enter == "slide":
                frames.append(slide_keyframes(ident, start, end, seq["hold_end"]))
            elif enter == "up":
                frames.append(
                    slide_keyframes(ident, start, end, seq["hold_end"], axis="Y")
                )
            else:
                frames.append(fade_keyframes(ident, start, end, seq["hold_end"]))
            if seq["address_bar"]:
                bar_ident = f"{name}-url-{index}"
                rules.append(
                    f"  {selector} .flow-bar .{prefix}{index} {{\n"
                    f"    animation-name: {bar_ident};\n  }}\n"
                )
                frames.append(
                    fade_keyframes(bar_ident, start + 2, end, seq["hold_end"])
                )
            if tap is None:
                continue
            tap_index = index + seq["tap_offset"]
            tap_class = f"{seq['tap_prefix']}{tap_index}"
            tap_ident = f"{name}-{seq['frame_tap']}{tap_index}"
            places.append(
                f"{selector} .{tap_class} {{\n"
                f"  --tap-x: {tap[0]}%;\n"
                f"  --tap-y: {tap[1]}%;\n"
                f"}}\n",
            )
            rules.append(
                f"  {selector} .{tap_class} {{\n"
                f"    animation: {tap_ident} {seconds}s{seq['delay']} infinite both;\n"
                f"  }}\n",
            )
            if len(tap) > TAP_COORDINATES:
                frames.append(swipe_keyframes(tap_ident, tap[2], tap[3], tap[4]))
            else:
                frames.append(tap_keyframes(tap_ident, tap[2], tap[3]))
    media = (
        "@media (prefers-reduced-motion: no-preference) {\n" + "\n".join(rules) + "}\n"
    )
    return HEADER + "\n" + "\n".join(places) + "\n" + media + "\n" + "\n".join(frames)


def main() -> None:
    """Write the complete generated stylesheet relative to this script."""
    path = Path(__file__).resolve().parent.parent / "css" / "sequences.css"
    path.write_text(generate(), encoding="utf-8")


if __name__ == "__main__":
    main()
